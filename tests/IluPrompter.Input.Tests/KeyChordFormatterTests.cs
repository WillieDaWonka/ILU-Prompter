using System.Windows.Input;
using IluPrompter.Core;

namespace IluPrompter.Input.Tests;

public class KeyChordFormatterTests
{
    [Theory]
    [InlineData(Key.Space, ModifierKeys.None, "Space")]
    [InlineData(Key.PageDown, ModifierKeys.None, "PageDown")]
    [InlineData(Key.PageUp, ModifierKeys.None, "PageUp")]
    [InlineData(Key.F5, ModifierKeys.None, "F5")]
    [InlineData(Key.Escape, ModifierKeys.None, "Escape")]
    [InlineData(Key.Home, ModifierKeys.None, "Home")]
    [InlineData(Key.Up, ModifierKeys.None, "Up")]
    [InlineData(Key.D0, ModifierKeys.None, "D0")]
    [InlineData(Key.NumPad0, ModifierKeys.None, "NumPad0")]
    [InlineData(Key.B, ModifierKeys.None, "B")]
    [InlineData(Key.OemComma, ModifierKeys.None, "OemComma")]
    [InlineData(Key.OemQuestion, ModifierKeys.None, "OemQuestion")]
    [InlineData(Key.Down, ModifierKeys.Shift, "Shift+Down")]
    [InlineData(Key.Down, ModifierKeys.Control, "Ctrl+Down")]
    [InlineData(Key.F4, ModifierKeys.Alt, "Alt+F4")]
    [InlineData(Key.PageDown, ModifierKeys.Control | ModifierKeys.Shift, "Ctrl+Shift+PageDown")]
    [InlineData(Key.PageDown, ModifierKeys.Shift | ModifierKeys.Alt | ModifierKeys.Control, "Ctrl+Alt+Shift+PageDown")]
    public void Formats_chords_in_canonical_modifier_order(Key key, ModifierKeys mods, string expected)
    {
        Assert.True(KeyChordFormatter.TryFormat(key, mods, out var chord));
        Assert.Equal(expected, chord);
    }

    [Fact]
    public void Matches_ControlIds_KeyChord()
    {
        Assert.True(KeyChordFormatter.TryFormat(Key.PageDown, ModifierKeys.Control | ModifierKeys.Alt | ModifierKeys.Shift, out var chord));
        Assert.Equal(ControlIds.KeyChord(true, true, true, "PageDown"), chord);
    }

    [Theory]
    [InlineData(Key.Return, "Enter")]
    [InlineData(Key.Prior, "PageUp")]
    [InlineData(Key.Next, "PageDown")]
    [InlineData(Key.Capital, "CapsLock")]
    public void Aliased_keys_have_one_pinned_name(Key key, string expected) =>
        Assert.Equal(expected, KeyChordFormatter.CanonicalName(key));

    [Fact]
    public void Key_System_uses_SystemKey()
    {
        // Alt+F4 arrives as Key.System with SystemKey = F4.
        Assert.True(KeyChordFormatter.TryFormat(Key.System, Key.F4, ModifierKeys.Alt, out var chord));
        Assert.Equal("Alt+F4", chord);

        // F10 arrives as Key.System with SystemKey = F10 and no Alt.
        Assert.True(KeyChordFormatter.TryFormat(Key.System, Key.F10, ModifierKeys.None, out chord));
        Assert.Equal("F10", chord);
    }

    [Theory]
    [InlineData(Key.LeftAlt)]
    [InlineData(Key.RightAlt)]
    [InlineData(Key.None)]
    public void Key_System_with_a_pure_modifier_is_ignored(Key systemKey) =>
        Assert.False(KeyChordFormatter.TryFormat(Key.System, systemKey, ModifierKeys.Alt, out _));

    [Theory]
    [InlineData(Key.LeftCtrl)]
    [InlineData(Key.RightCtrl)]
    [InlineData(Key.LeftShift)]
    [InlineData(Key.RightShift)]
    [InlineData(Key.LeftAlt)]
    [InlineData(Key.RightAlt)]
    [InlineData(Key.LWin)]
    [InlineData(Key.RWin)]
    public void Pure_modifier_presses_are_ignored(Key key) =>
        Assert.False(KeyChordFormatter.TryFormat(key, ModifierKeys.Control | ModifierKeys.Shift, out _));

    [Theory]
    [InlineData(Key.ImeProcessed)]
    [InlineData(Key.DeadCharProcessed)]
    public void Ime_and_dead_char_processing_is_ignored(Key key) =>
        Assert.False(KeyChordFormatter.TryFormat(key, Key.A, ModifierKeys.None, out _));

    [Fact]
    public void Anything_with_the_windows_key_held_is_ignored()
    {
        Assert.False(KeyChordFormatter.TryFormat(Key.D, ModifierKeys.Windows, out _));
        Assert.False(KeyChordFormatter.TryFormat(Key.D, ModifierKeys.Windows | ModifierKeys.Shift, out _));
    }

    [Fact]
    public void Default_binding_chords_are_producible()
    {
        // Every key chord in the factory defaults can be generated by the bridge.
        var produced = new HashSet<string>
        {
            "F5", "F8", "F11", "Space", "Escape", "Down", "Up", "Shift+Down", "Shift+Up", "Right", "Left",
            "PageDown", "PageUp", "Ctrl+Down", "Ctrl+Up", "Home", "B", "M", "D0", "NumPad0",
        };
        var keys = new (Key Key, ModifierKeys Mods)[]
        {
            (Key.F5, 0), (Key.F8, 0), (Key.F11, 0), (Key.Space, 0), (Key.Escape, 0), (Key.Down, 0), (Key.Up, 0),
            (Key.Down, ModifierKeys.Shift), (Key.Up, ModifierKeys.Shift), (Key.Right, 0), (Key.Left, 0),
            (Key.Next, 0), (Key.Prior, 0), (Key.Down, ModifierKeys.Control), (Key.Up, ModifierKeys.Control),
            (Key.Home, 0), (Key.B, 0), (Key.M, 0), (Key.D0, 0), (Key.NumPad0, 0),
        };
        var actual = new HashSet<string>();
        foreach (var (key, mods) in keys)
        {
            Assert.True(KeyChordFormatter.TryFormat(key, mods, out var chord));
            actual.Add(chord);
        }

        Assert.Equal(produced, actual);

        foreach (var chord in DefaultBindings.KeyboardGlobal.Keys.Concat(DefaultBindings.KeyboardTransport.Keys))
        {
            Assert.Contains(chord, actual);
        }
    }
}
